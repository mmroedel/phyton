#6.	Dobro, Triplo e Raiz Quadrada: Crie um algoritmo que leia um número e mostre o seu dobro, triplo e raiz quadrada.
numero=int(input("Digite um número: "))
dobro=numero*2
triplo=numero*3
raiz=(numero ** 0.5)
print(f"O número digitado é {numero}! O dobro deste número é {dobro}. O triplo deste número é {triplo} e a raiz quadrada deste número é {raiz}")
