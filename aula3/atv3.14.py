salario=float(input("Insira o seu salário para calcularmos o seu aumento de 15%: "))
aumento= salario*0.15
salarionovo=salario+aumento
print(f"Parabéns pela promossão. Seu aumento foi de R${aumento}. Agora seu salário é de R${salarionovo}!")